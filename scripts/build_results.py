"""Build docs/RESULTS.md from the project's own result files (nothing is typed in by hand).

    python scripts/build_results.py

Reads (whatever exists; anything missing is reported as "not run yet"):
  config/severity_calibration.json         alert limits, severity rule, model per machine
  reports/phase2/metrics_by_group.csv      held-out test ROC-AUC per machine (Phase 2)
  reports/phase3/sanity_level_baseline.csv loudness-only baseline (Phase 3)
  reports/identification/summary.txt       machine identification investigation
  reports/robustness/metrics.csv           0 dB / -6 dB robustness test (Phase 8)
Run it again whenever one of those files changes, then commit docs/RESULTS.md.
"""
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

import pandas as pd

from smart_listener import profiles
from smart_listener.config import load_config, project_root


def md_table(headers, rows) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def fmt(v, nd=3):
    return "-" if v is None or (isinstance(v, float) and pd.isna(v)) else f"{v:.{nd}f}"


def build(root: Path) -> str:
    cfg = load_config()
    L = ["# Smart Listener - results", "",
         f"Generated by `scripts/build_results.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC from the result files "
         "in this repository. Every number below comes from those files.", ""]

    # ---- limits and rule
    cal_path = root / "config" / "severity_calibration.json"
    L += ["## 1. Alert limits and severity rule", ""]
    if cal_path.exists():
        cal = json.loads(cal_path.read_text(encoding="utf-8"))
        t, r = cal["thresholds"], cal.get("rule", {})
        L += [f"- Warning limit: z > **{t['z_warn']:.2f}**; alarm limit: z > **{t['z_alarm']:.2f}** "
              "(the same for every machine, because each machine's scores are first converted to a calibrated z).",
              f"- HIGH: at least {r.get('k_high', '?')} of the last {r.get('m_high', '?')} ten-second windows above the "
              f"alarm limit. WARNING: at least {r.get('k_warn', '?')} of the last {r.get('n_window', '?')} windows above "
              f"the warning limit" + (" (or one window above the alarm limit)" if r.get("single_alarm_warning") else "")
              + ". WATCH: a single window above the warning limit. The level only goes down after "
              f"{r.get('recover', '?')} clean windows; a HIGH that returns within {r.get('cooldown', '?')} windows "
              "re-opens the same incident.",
              "- Limits were calibrated on normal validation recordings only; test recordings were never used to set them.", ""]
    else:
        L += ["Not run yet (`scripts/calibrate_severity.py`).", ""]

    # ---- detector quality
    L += ["## 2. Detector quality per machine (held-out test recordings, 6 dB)", ""]
    prof = profiles.model_profiles(cfg, root)
    if any(p["test_auc"] is not None for p in prof):
        rows = []
        for p in prof:
            ci = f"{fmt(p['test_auc_low'])}-{fmt(p['test_auc_high'])}" if p["test_auc_low"] is not None else "-"
            rows.append([p["group"], p["model"] or "-", fmt(p["test_auc"]), ci, fmt(p["loudness_auc"]),
                         "yes" if p["caution"] else ""])
        L += [md_table(["Machine", "Model", "Test ROC-AUC", "95% interval", "Loudness-only ROC-AUC",
                        "Caution (loudness does as well)"], rows), "",
              "ROC-AUC: 0.5 = no better than chance, 1.0 = normal and abnormal fully separated. Test sets hold equal "
              "numbers of normal and abnormal clips, so precision in a real plant (where faults are rare) would be lower.", ""]
    else:
        L += ["Not available (`scripts/evaluate_ad.py` writes reports/phase2/metrics_by_group.csv).", ""]

    # ---- identification
    L += ["## 3. Automatic machine identification (investigation)", ""]
    ident = root / "reports" / "identification" / "summary.txt"
    val = root / "reports" / "identification" / "validation.json"
    if ident.exists():
        status = ""
        if val.exists():
            v = json.loads(val.read_text(encoding="utf-8"))
            status = ("**Decision: suggestions ON.**" if v.get("enabled") else
                      f"**Decision: suggestions OFF; the machine is selected manually.** Reason: {v.get('reason', '')}")
        L += [status, "", "Full output of `scripts/investigate_identification.py`:", "", "```",
              ident.read_text(encoding="utf-8").strip(), "```", ""]
    else:
        L += ["Not run yet (`scripts/investigate_identification.py`).", ""]

    # ---- robustness
    L += ["## 4. Robustness to louder background noise (0 dB and -6 dB test recordings)", ""]
    rob = root / "reports" / "robustness" / "metrics.csv"
    if rob.exists():
        df = pd.read_csv(rob).sort_values(["group", "snr_db"], ascending=[True, False])
        rows = [[r["group"], int(r["snr_db"]), fmt(r["auc"]),
                 "" if int(r["snr_db"]) == 6 else f"{r['auc_change_vs_6db']:+.3f}",
                 f"{r['normal_above_warning_pct']:.1f}%", f"{r['normal_above_alarm_pct']:.1f}%",
                 f"{r['abnormal_above_alarm_pct']:.1f}%"] for _, r in df.iterrows()]
        snrs = sorted(df["snr_db"].unique())
        L += [f"SNR levels scored: {', '.join(f'{s} dB' for s in snrs)}. Models and alert limits are the 6 dB ones; "
              "nothing was retrained or re-tuned. Only TEST-split recordings were used.", "",
              md_table(["Machine", "SNR (dB)", "ROC-AUC", "Change vs 6 dB", "Normal > warning", "Normal > alarm",
                        "Abnormal > alarm"], rows), "",
              "Normal > warning / alarm = false warnings / alarms per 10-second window. Abnormal > alarm = detections per "
              "window. HIGH needs several windows above the alarm limit, so these are not incident rates.", ""]
        if (root / "reports" / "robustness" / "auc_by_snr.png").exists():
            L += ["![ROC-AUC by noise level](../reports/robustness/auc_by_snr.png)", ""]
    else:
        L += ["Not run yet (`scripts/robustness_snr.py`, see docs/TECHNICAL.md).", ""]

    L += ["## 5. What these results do not show", "",
          "- The models detect how unlike its learned normal sound a machine is. They do not diagnose the physical "
          "fault, predict failure time or give a probability of failure.",
          "- All results come from the MIMII dataset (laboratory recordings of 8 machines). Performance on other "
          "machines, microphones or factories has not been measured.",
          "- Simulated monitoring replays recorded MIMII clips; it is not a live microphone connection.", ""]
    return "\n".join(L)


def main() -> int:
    root = project_root()
    text = build(root)
    out = root / "docs" / "RESULTS.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
