"""Phase 8: the documentation stays in step with the code."""
import re
from pathlib import Path

from fastapi.routing import APIRoute

from smart_listener import api

ROOT = Path(__file__).resolve().parents[1]
DOCS = ["README.md", "docs/USER_GUIDE.md", "docs/TECHNICAL.md", "docs/SECURITY.md", "docs/DEMO_SCRIPT.md"]


def test_docs_exist_and_relative_links_resolve():
    for d in DOCS:
        p = ROOT / d
        assert p.exists(), d
        for link in re.findall(r"\]\(([^)#]+)\)", p.read_text(encoding="utf-8")):
            if link.startswith("http"):
                continue
            if link == "RESULTS.md" or link.endswith("/RESULTS.md"):
                continue                              # generated by scripts/build_results.py
            assert (p.parent / link).exists(), (d, link)


def test_every_api_route_is_documented(tmp_path):
    text = (ROOT / "docs" / "TECHNICAL.md").read_text(encoding="utf-8")
    app = api.create_app(db_path=tmp_path / "r.db")
    paths = {r.path for r in app.routes if isinstance(r, APIRoute)}
    simplified = {re.sub(r"\{[^}]+\}", "{id}", p) for p in paths}
    missing = [p for p in simplified if p not in text]
    assert not missing, missing


def test_docs_make_no_failure_prediction_claims():
    for d in DOCS:
        t = (ROOT / d).read_text(encoding="utf-8").lower()
        for bad in ("predicts failure", "remaining useful life is", "probability of failure is", "diagnoses the fault"):
            assert bad not in t, (d, bad)


def test_results_page_builds_without_any_result_files(tmp_path, monkeypatch):
    import importlib.util
    spec = importlib.util.spec_from_file_location("build_results", ROOT / "scripts" / "build_results.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    text = mod.build(tmp_path)
    assert text.count("Not run yet") >= 2 and "Not available" in text
    assert "does not" not in text or "do not diagnose" in text
